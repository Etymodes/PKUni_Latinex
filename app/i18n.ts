export function availableLearningLanguages(locale: UiLocale) {
  const excluded = locale === "en" ? "en-us" : "zh-mandarin";
  return learningLanguages.filter((language) => language.id !== excluded);
}

export function normalizeLearningLanguage(locale: UiLocale, value: string): LearningLanguageId {
  const available = availableLearningLanguages(locale);
  if (available.some((language) => language.id === value)) return value as LearningLanguageId;
  return locale === "en" ? "zh-mandarin" : "en-us";
}

export function getLearningLanguage(id: string) {
  return learningLanguages.find((language) => language.id === id) || learningLanguages.find((language) => language.id === "la")!;
}

